def validate(chapters: list[dict]) -> list[str]:
    """返回校验错误列表（空 = 通过）。"""
    errors = []
    for ch in chapters:
        nums = []
        for i, q in enumerate(ch["questions"], 1):
            tag = f"[{ch['name']} 第{i}题]"
            if not str(q.get("stem") or "").strip():
                errors.append(f"{tag} 题干为空")
            if not str(q.get("answer") or "").strip():
                errors.append(f"{tag} 答案为空")
            if q.get("type") == "cloze":
                blanks = q.get("blanks") or []
                if not blanks:
                    errors.append(f"{tag} cloze 无空位数据")
                    continue
                for bi, b in enumerate(blanks, 1):
                    bopts = b.get("options") or []
                    if len(bopts) < 2:
                        errors.append(f"{tag} 空{bi} 选项少于2个")
                    bans = str(b.get("answer") or "").strip().upper()
                    if not bans or not re.fullmatch(r"[A-H]", bans):
                        errors.append(f"{tag} 空{bi} 答案非单字母A-H: {b.get('answer')}")
                    elif ord(bans) - ord("A") >= len(bopts):
                        errors.append(f"{tag} 空{bi} 答案 {bans} 超出选项范围")
                num = q.get("num")
                if not str(num or "").strip():
                    errors.append(f"{tag} 题号为空")
                else:
                    nums.append(str(num))
                continue
            if q.get("type") != "choice":
                errors.append(f"{tag} 非选择题类型: {q.get('type')}")
                continue
            opts = q.get("options") or []
            if len(opts) < 2:
                errors.append(f"{tag} 选项少于2个")
            ans = re.sub(r"[^A-H]", "", str(q["answer"]).upper())
            if not ans or not re.fullmatch(r"[A-H]+", ans):
                errors.append(f"{tag} 选择题答案非A-H字母: {q['answer']}")
            else:
                for ch_ in ans:
                    if ord(ch_) - ord("A") >= len(opts):
                        errors.append(f"{tag} 答案 {ch_} 超出选项范围")
            num = q.get("num")
            if not str(num or "").strip():
                errors.append(f"{tag} 题号为空")
            else:
                nums.append(str(num))
        # 题号库内唯一（允许跳号，不要求连续）
        if len(nums) != len(set(nums)):
            from collections import Counter
            dup = [n for n, c in Counter(nums).items() if c > 1]
            errors.append(f"[{ch['name']}] 题号重复: {dup}")
    return errors


def dry_run() -> None:
    chapters = [CH1, CH2, CH3, CH4, CH5]
    errors = validate(chapters)
    if errors:
        print("== 校验失败 ==")
        for e in errors:
            print(" -", e)
        sys.exit(1)
    print("== 校验通过 ==")
    total = 0
    for ch in chapters:
        multi = sum(1 for q in ch["questions"]
                    if len(re.sub(r"[^A-H]", "", str(q["answer"]).upper())) > 1)
        total += len(ch["questions"])
        print(f"\n### {ch['name']}：共 {len(ch['questions'])} 题（多选/多空 {multi} 题）")
        for q in ch["questions"]:
            if q.get("type") == "cloze":
                print(f"  {q['num']}. {q['stem']}")
                for bi, b in enumerate(q.get("blanks") or [], 1):
                    bopts = b.get("options") or []
                    bans = re.sub(r"[^A-H]", "", str(b.get("answer") or "").upper())
                    bans_txt = "、".join(
                        f"{c}.{bopts[ord(c) - ord('A')]}" for c in bans)
                    print(f"     空{bi}: {' / '.join(chr(ord('A') + j) + '. ' + o for j, o in enumerate(bopts))} => {bans_txt}")
                continue
            letters = re.sub(r"[^A-H]", "", str(q["answer"]).upper())
            ans = "、".join(
                f"{c}.{q['options'][ord(c) - ord('A')]}" for c in letters)
            print(f"  {q['num']}. {q['stem']}")
            for j, o in enumerate(q["options"]):
                print(f"     {chr(ord('A') + j)}. {o}")
            print(f"     答案: {ans}")
    print(f"\n合计：{total} 题")


def install(user: str = "LiZF") -> None:
    from app import UserData, new_bank_id, now_str  # noqa: E402
    from lykie import folders as lykie_folders  # noqa: E402
    from lykie import settle as lykie_settle  # noqa: E402
    from lykie.import_rules import attach_question_defaults  # noqa: E402

    chapters = [CH1, CH2, CH3, CH4, CH5]
    errors = validate(chapters)
    if errors:
        print("校验失败，中止安装：")
        for e in errors:
            print(" -", e)
        sys.exit(1)

    store = UserData(user)
    existing = {b["name"] for b in store.banks}
    for ch in chapters:
        if ch["name"] in existing:
            print(f"跳过（已存在同名题库）: {ch['name']}")
            continue
        questions = [
            attach_question_defaults(q, i)
            for i, q in enumerate(ch["questions"], 1)
        ]
        folder, err = lykie_folders.ensure_folder(store, FOLDER_NAME)
        if not folder:
            print(f"建文件夹失败: {err}")
            sys.exit(1)
        bank = {
            "id": new_bank_id(),
            "name": ch["name"],
            "imported_at": now_str(),
            "questions": questions,
            "folder_id": folder["id"],
        }
        lykie_settle.ensure_bank_runs(bank)
        store.banks.append(bank)
        print(f"{user} <- {ch['name']} (id={bank['id']}, "
              f"{len(questions)}题, 文件夹={folder['name']})")
    store.save()
    print("完成。")


if __name__ == "__main__":
    if "--install" in sys.argv:
        install()
    else:
        dry_run()
